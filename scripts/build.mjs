import {readFile,writeFile,mkdir} from 'node:fs/promises';
await mkdir('dist',{recursive:true});
const html=await readFile('src/index.html','utf8');
const css=(await readFile('src/style.css','utf8'))+'\n'+await readFile('src/social.css','utf8')+'\n'+await readFile('src/light.css','utf8');
const catalog=await readFile('src/catalog.js','utf8');
const engine=(await readFile('src/engine.js','utf8')).replace(/^import .*?;\n/gm,'');
const projects=await readFile('src/projects.js','utf8');
const feed=(await readFile('src/feed.js','utf8')).replace(/^import .*?;\n/gm,'');
const app=(await readFile('src/app.js','utf8')).replace(/^import .*?;\n/gm,'');
await writeFile('dist/index.html',html.replace('/* STYLES */',css).replace('/* APPLICATION */',catalog.replaceAll('export ','')+'\n'+engine.replaceAll('export ','')+'\n'+projects.replaceAll('export ','')+'\n'+feed.replaceAll('export ','')+'\n'+app));
console.log('Built dist/index.html (standalone, no external dependencies)');
